import type { RecipeDefinition, RecipeProduct } from './recipe-types';
import type { RecipeId, ToolId } from './types';
const p = (kind: string, label: string, amount = 1): RecipeProduct => ({ kind, label, amount });
function recipe(
  id: RecipeId,
  title: string,
  category: RecipeDefinition['category'],
  ingredients: RecipeProduct[],
  result: RecipeProduct,
  description: string,
  tool?: ToolId,
): RecipeDefinition {
  return {
    id,
    title,
    category,
    availability: 'active',
    hint: title,
    ingredients,
    result,
    description,
    ...(tool ? { tool } : {}),
  };
}
