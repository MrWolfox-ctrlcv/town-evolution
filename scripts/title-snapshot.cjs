/** Generated title data is checked against source inputs before shipping a preview. */
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const target = 'assets/scripts/application/TitleSnapshot.ts';
const hash = (value) => createHash('sha256').update(value).digest('hex');
function sourceHash(base = root) {
  const files = [
    'assets/scripts/application/TitleIsland.ts',
    'scripts/title-snapshot.cjs',
    'tsconfig.domain.json',
  ];
  function walk(relative) {
    for (const entry of fs.readdirSync(path.join(base, relative), { withFileTypes: true })) {
      const name = `${relative}/${entry.name}`;
      if (entry.isDirectory()) walk(name);
      else if (entry.name.endsWith('.ts')) files.push(name);
    }
  }
  walk('assets/scripts/domain');
  const digest = createHash('sha256');
  for (const file of files.sort())
    digest
      .update(file)
      .update('\0')
      .update(fs.readFileSync(path.join(base, file), 'utf8').replace(/\r\n/g, '\n'))
      .update('\0');
  return digest.digest('hex');
}
function readConstants(filename) {
  const source = fs.readFileSync(filename, 'utf8');
  const ast = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true),
    values = {};
  for (const statement of ast.statements)
    if (ts.isVariableStatement(statement))
      for (const declaration of statement.declarationList.declarations)
        if (
          ts.isIdentifier(declaration.name) &&
          declaration.initializer &&
          (ts.isStringLiteral(declaration.initializer) ||
            ts.isNumericLiteral(declaration.initializer))
        )
          values[declaration.name.text] = ts.isNumericLiteral(declaration.initializer)
            ? Number(declaration.initializer.text)
            : declaration.initializer.text;
  return values;
}
function readSnapshot(base = root) {
  return readConstants(path.join(base, target));
}
function verifySnapshot(base = root) {
  const stale = () => {
    throw new Error(
      'Title snapshot is missing, changed or out of date. Run npm run title:snapshot and review the resulting template.',
    );
  };
  let data;
  try {
    data = readSnapshot(base);
  } catch {
    stale();
  }
  if (
    data.TITLE_SNAPSHOT_SOURCE_HASH !== sourceHash(base) ||
    typeof data.TITLE_SNAPSHOT_JSON !== 'string' ||
    hash(data.TITLE_SNAPSHOT_JSON) !== data.TITLE_SNAPSHOT_DATA_HASH
  )
    stale();
  JSON.parse(data.TITLE_SNAPSHOT_JSON);
  return {
    sourceHash: data.TITLE_SNAPSHOT_SOURCE_HASH,
    dataHash: data.TITLE_SNAPSHOT_DATA_HASH,
    bytes: Buffer.byteLength(data.TITLE_SNAPSHOT_JSON),
  };
}
function checkDiagnostics(diagnostics) {
  if (diagnostics.length)
    throw new Error(
      ts.formatDiagnosticsWithColorAndContext(diagnostics, {
        getCanonicalFileName: (name) => name,
        getCurrentDirectory: () => root,
        getNewLine: () => '\n',
      }),
    );
}
async function generate() {
  // Compile only the authoritative domain graph. A missing/broken generated cache must not
  // prevent regeneration, and an old .domain-build tree must never become the source of truth.
  const settings = ts.readConfigFile(path.join(root, 'tsconfig.domain.json'), ts.sys.readFile);
  if (settings.error)
    throw new Error(ts.flattenDiagnosticMessageText(settings.error.messageText, '\n'));
  const config = ts.parseJsonConfigFileContent(settings.config, ts.sys, root);
  const options = config.options;
  if (
    !options.rootDir ||
    path.resolve(options.rootDir) !== path.resolve(root, 'assets/scripts') ||
    !options.outDir ||
    path.resolve(options.outDir) !== path.resolve(root, '.domain-build') ||
    options.module !== ts.ModuleKind.CommonJS ||
    options.noEmit ||
    options.emitDeclarationOnly
  )
    throw new Error(
      'Title generator requires CommonJS JavaScript output in .domain-build, with rootDir assets/scripts.',
    );
  const program = ts.createProgram([path.join(root, 'assets/scripts/domain/demo.ts')], options);
  checkDiagnostics([...config.errors, ...ts.getPreEmitDiagnostics(program)]);
  const emitted = program.emit();
  // A write failure can report TS5033 even with emitSkipped=false. Never read old output.
  checkDiagnostics(emitted.diagnostics);
  if (emitted.emitSkipped) throw new Error('Current demo generation code could not compile');
  const { createDemoGame } = require('../.domain-build/domain/demo');
  const { TITLE_ISLAND_TIME } = readConstants(
    path.join(root, 'assets/scripts/application/TitleIsland.ts'),
  );
  if (!Number.isSafeInteger(TITLE_ISLAND_TIME))
    throw new Error('Title display clock must be a fixed safe integer');
  const data = JSON.stringify(createDemoGame(TITLE_ISLAND_TIME));
  const output =
    '/** Generated by npm run title:snapshot. Do not edit; source and content hashes are checked before preview builds. */\n' +
    `export const TITLE_SNAPSHOT_SOURCE_HASH = ${JSON.stringify(sourceHash())};\n` +
    `export const TITLE_SNAPSHOT_DATA_HASH = ${JSON.stringify(hash(data))};\n` +
    `export const TITLE_SNAPSHOT_JSON: string = ${JSON.stringify(data)};\n`;
  const formatted = await require('prettier').format(output, {
    ...(await require('prettier').resolveConfig(path.join(root, target))),
    filepath: target,
  });
  fs.writeFileSync(path.join(root, target), formatted);
  return verifySnapshot();
}
module.exports = { sourceHash, readSnapshot, verifySnapshot };
if (require.main === module)
  Promise.resolve()
    .then(() => (process.argv.includes('--check') ? verifySnapshot() : generate()))
    .then((result) => console.log('Title snapshot verified:', JSON.stringify(result)))
    .catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
